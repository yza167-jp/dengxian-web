import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendorRoot = join(projectRoot, 'vendor', 'mofa-dengxiantai');
const commit = readFileSync(join(vendorRoot, 'UPSTREAM_COMMIT'), 'utf8').trim();

function parseCsv(text) {
  const source = text.replace(/^\uFEFF/, '');
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;

  for (let index = 0; index < source.length; index += 1) {
    const char = source[index];
    if (quoted) {
      if (char === '"' && source[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        field += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n') {
      row.push(field.replace(/\r$/, ''));
      rows.push(row);
      row = [];
      field = '';
    } else {
      field += char;
    }
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field.replace(/\r$/, ''));
    rows.push(row);
  }

  const [headers, ...data] = rows.filter((candidate) => candidate.some(Boolean));
  if (!headers) throw new Error('CSV is empty');
  return data.map((values) =>
    Object.fromEntries(headers.map((header, index) => [header, values[index] ?? ''])),
  );
}

const sources = {
  characters: 'characters.csv',
  opportunities: 'opportunity-cards.csv',
  calamities: 'calamity-cards.csv',
  fates: 'fate-cards.csv',
};

const content = Object.fromEntries(
  Object.entries(sources).map(([key, filename]) => [
    key,
    parseCsv(readFileSync(join(vendorRoot, 'cards', filename), 'utf8')),
  ]),
);

const expected = { characters: 14, opportunities: 48, calamities: 18, fates: 12 };
for (const [key, count] of Object.entries(expected)) {
  if (content[key].length !== count) {
    throw new Error(`Expected ${count} ${key}, received ${content[key].length}`);
  }
}

const output = `/* This file is generated by scripts/sync-upstream.mjs. Do not edit by hand. */
export const UPSTREAM_COMMIT = ${JSON.stringify(commit)} as const;
export const upstreamCharacters = ${JSON.stringify(content.characters, null, 2)} as const;
export const upstreamOpportunities = ${JSON.stringify(content.opportunities, null, 2)} as const;
export const upstreamCalamities = ${JSON.stringify(content.calamities, null, 2)} as const;
export const upstreamFates = ${JSON.stringify(content.fates, null, 2)} as const;
`;

writeFileSync(join(projectRoot, 'src', 'shared', 'data', 'upstream.generated.ts'), output);
console.log(
  `Synced ${content.characters.length + content.opportunities.length + content.calamities.length + content.fates.length} upstream rows from ${commit.slice(0, 12)}`,
);
